import type { JsonValue } from '../../json/types';
import {
  type GeneratedCode,
  type ModelClass,
  type TypeModel,
  type TypeRef,
  classesFromRoot,
  inferTypeModel,
} from '../model';
import { NameScope, isPlainIdentifier, toIdentifier, toPascalCase } from '../naming';

export interface TypeScriptOptions {
  rootName: string;
  declaration: 'interface' | 'type';
  exportTypes: boolean;
  readonly: boolean;
  arrayStyle: 'brackets' | 'generic';
  /** Represent ISO date strings as `string` (JSON reality) or `Date` (after your own revival). */
  dateType: 'string' | 'Date';
  detectDictionaries: boolean;
}

export const DEFAULT_TYPESCRIPT_OPTIONS: TypeScriptOptions = {
  rootName: 'Root',
  declaration: 'interface',
  exportTypes: true,
  readonly: false,
  arrayStyle: 'brackets',
  dateType: 'string',
  detectDictionaries: true,
};

const RESERVED_TYPE_NAMES = [
  'Object',
  'String',
  'Number',
  'Boolean',
  'Array',
  'Record',
  'Date',
  'Map',
  'Set',
  'Promise',
  'Partial',
  'Required',
  'Readonly',
  'Error',
  'Function',
  'Symbol',
  'JSON',
  'Math',
];

export function generateTypeScript(
  value: JsonValue,
  options: Partial<TypeScriptOptions> = {},
): GeneratedCode {
  const o: TypeScriptOptions = { ...DEFAULT_TYPESCRIPT_OPTIONS, ...options };
  const model = inferTypeModel(value, {
    rootName: o.rootName,
    detectDictionaries: o.detectDictionaries,
    detectUuids: false,
  });
  return generateTypeScriptFromModel(model, o);
}

/** Emits TypeScript for an existing type model; `header` replaces the JSON usage hint. */
export function generateTypeScriptFromModel(
  model: TypeModel,
  options: Partial<TypeScriptOptions> = {},
  header?: string,
): GeneratedCode {
  const o: TypeScriptOptions = { ...DEFAULT_TYPESCRIPT_OPTIONS, ...options };
  const notes: string[] = [];
  const scope = new NameScope(RESERVED_TYPE_NAMES);
  const names = new Map<string, string>();
  for (const c of classesFromRoot(model)) {
    const wanted = toIdentifier(c.name, toPascalCase, 'Item');
    const name = scope.has(wanted) ? scope.claim(`${wanted}Model`) : scope.claim(wanted);
    if (name !== c.name) notes.push(`Type "${c.name}" was named "${name}" to avoid a conflict.`);
    names.set(c.name, name);
  }

  const wrapArray = (inner: string, complex: boolean) =>
    o.arrayStyle === 'generic' ? `Array<${inner}>` : complex ? `(${inner})[]` : `${inner}[]`;

  const typeOf = (t: TypeRef): string => {
    let base: string;
    switch (t.kind) {
      case 'string':
        base =
          (t.format === 'date-time' || t.format === 'date') && o.dateType === 'Date'
            ? 'Date'
            : 'string';
        break;
      case 'integer':
      case 'number':
        base = 'number';
        break;
      case 'boolean':
        base = 'boolean';
        break;
      case 'any':
        return 'unknown';
      case 'class':
        base = names.get(t.name) ?? t.name;
        break;
      case 'union':
        base = [...new Set(t.types.map(typeOf))].join(' | ');
        break;
      case 'array': {
        const inner = typeOf(t.items);
        base = wrapArray(inner, inner.includes('|'));
        break;
      }
      case 'dictionary':
        base = `Record<string, ${typeOf(t.values)}>`;
        break;
    }
    return t.nullable ? `${base} | null` : base;
  };

  const ro = o.readonly ? 'readonly ' : '';
  const exp = o.exportTypes ? 'export ' : '';
  const emit = (c: ModelClass): string => {
    const name = names.get(c.name) ?? c.name;
    const members = c.properties.map((p) => {
      const key = isPlainIdentifier(p.jsonName) ? p.jsonName : JSON.stringify(p.jsonName);
      return `  ${ro}${key}${p.optional ? '?' : ''}: ${typeOf(p.type)};`;
    });
    return o.declaration === 'interface'
      ? `${exp}interface ${name} {\n${members.join('\n')}\n}`
      : `${exp}type ${name} = {\n${members.join('\n')}\n};`;
  };

  const blocks = classesFromRoot(model).map(emit);
  const root = names.get(model.rootClass) ?? model.rootClass;
  if (model.rootIsArray) blocks.push(`${exp}type ${root}List = ${wrapArray(root, false)};`);
  const usage = model.rootIsArray ? `${root}List` : root;
  const code = `${header ?? `// Generated by DevStudio. Usage: const data = JSON.parse(json) as ${usage};`}\n\n${blocks.join('\n\n')}\n`;
  return { code, files: [{ path: 'types.ts', content: code }], notes };
}
