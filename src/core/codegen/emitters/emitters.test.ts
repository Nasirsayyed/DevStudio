import { describe, expect, it } from 'vitest';
import { SAMPLE_ORDER_JSON } from '../../json/samples';
import type { JsonValue } from '../../json/types';
import { generateCSharp } from './csharp';
import { generateJava } from './java';
import { generatePython } from './python';
import { generateSqlTable } from './sqlTable';
import { generateTypeScript } from './typescript';

const order = JSON.parse(SAMPLE_ORDER_JSON) as JsonValue;
const spec = { order_id: 1001, customer_name: 'Ahmed', total_amount: 2500.5 };

describe('C#', () => {
  it('generates the specification example exactly', () => {
    expect(generateCSharp(spec).code)
      .toBe(`// Generated by DevStudio. Deserialize with: JsonSerializer.Deserialize<Root>(json)
#nullable enable

using System.Text.Json.Serialization;

namespace MyApp.Models;

public class Root
{
    [JsonPropertyName("order_id")]
    public int OrderId { get; set; }

    [JsonPropertyName("customer_name")]
    public string CustomerName { get; set; } = string.Empty;

    [JsonPropertyName("total_amount")]
    public double TotalAmount { get; set; }
}
`);
  });

  it('supports nullable value/reference types, lists, dictionaries and nested classes', () => {
    const code = generateCSharp({
      id: null,
      name: null,
      tags: ['a'],
      scores: { '1': 2 },
      child: { x: 1 },
      items: [{ n: 1 }, {}],
    }).code;
    expect(code).toContain('public object? Id { get; set; }');
    expect(code).toContain('public object? Name { get; set; }');
    expect(code).toContain('public List<string> Tags { get; set; } = new();');
    expect(code).toContain('public Dictionary<string, int> Scores { get; set; } = new();');
    expect(code).toContain('public Child Child { get; set; } = new();');
    expect(code).toContain('public int? N { get; set; }');
    expect(code).toContain('using System.Collections.Generic;');
    const nullableRef = generateCSharp({ items: [{ s: 'a' }, { s: null }, {}] }).code;
    expect(nullableRef).toContain('public string? S { get; set; }');
  });

  it('honors namespace, root name, records, required, attributes and number/date options', () => {
    const code = generateCSharp(order, {
      namespace: 'acme.shop models',
      fileScopedNamespace: false,
      rootName: 'order',
      typeKind: 'record',
      requiredMembers: true,
      attributes: 'newtonsoft',
      attributeMode: 'when-different',
      numberType: 'decimal',
      dateType: 'DateTimeOffset',
      collectionType: 'IReadOnlyList',
      nullableReferenceTypes: false,
    }).code;
    expect(code).toContain('namespace Acme.ShopModels\n{');
    expect(code).toContain('    public record Order');
    expect(code).toContain(
      '        [JsonProperty("order_id")]\n        public required int OrderId { get; init; }',
    );
    expect(code).toContain('public required decimal TotalAmount { get; init; }');
    expect(code).toContain('public required DateTimeOffset CreatedAt { get; init; }');
    expect(code).toContain('public required IReadOnlyList<Item> Items { get; init; }');
    expect(code).toContain('using Newtonsoft.Json;');
    expect(code).not.toContain('#nullable enable');
    expect(code).not.toContain('= new();');
  });

  it('keeps identifiers valid and unique', () => {
    const r = generateCSharp({
      root: 1,
      'user id': 2,
      userId: 3,
      '2fa': true,
      '': 'x',
      Object: { a: 1 },
    });
    expect(r.code).toContain('public int RootValue { get; set; }'.replace('RootValue', 'Root2'));
    expect(r.code).toContain('public int UserId { get; set; }');
    expect(r.code).toContain('public int UserId2 { get; set; }');
    expect(r.code).toContain('public bool _2fa { get; set; }');
    expect(r.code).toContain('public string Value { get; set; } = string.Empty;');
    expect(r.code).toContain('public class ObjectModel');
    expect(r.notes.length).toBeGreaterThan(0);
  });

  it('produces one file per class with only the needed usings, and List<T> usage for root arrays', () => {
    const r = generateCSharp([{ when: '2026-01-01T00:00:00Z', child: { n: 1 } }]);
    expect(r.code).toContain('JsonSerializer.Deserialize<List<Root>>(json)');
    expect(r.files.map((f) => f.path)).toEqual(['Root.cs', 'Child.cs']);
    expect(r.files[0]!.content).toContain('using System;');
    expect(r.files[1]!.content).not.toContain('using System;\n');
  });
});

describe('TypeScript', () => {
  it('generates interfaces with optional, nullable and quoted properties', () => {
    const code = generateTypeScript({
      id: 1,
      'first name': 'a',
      items: [{ n: 1, x: null }, { n: 2 }],
      map: { '1': true },
    }).code;
    expect(code).toContain(
      'export interface Root {\n  id: number;\n  "first name": string;\n  items: Item[];\n  map: Record<string, boolean>;\n}',
    );
    expect(code).toContain('export interface Item {\n  n: number;\n  x?: unknown;\n}');
  });

  it('supports type aliases, readonly, generic arrays, Date and root arrays', () => {
    const code = generateTypeScript([{ when: '2026-01-01T00:00:00Z', v: [1, 'a'] }], {
      declaration: 'type',
      readonly: true,
      arrayStyle: 'generic',
      dateType: 'Date',
      exportTypes: false,
    }).code;
    expect(code).toContain(
      'type Root = {\n  readonly when: Date;\n  readonly v: Array<string | number>;\n};',
    );
    expect(code).toContain('type RootList = Array<Root>;');
  });
});

describe('Java', () => {
  it('generates Jackson-annotated classes with nested static classes and getters/setters', () => {
    const r = generateJava(order);
    expect(r.code).toContain('package com.example.model;');
    expect(r.code).toContain('import java.time.OffsetDateTime;');
    expect(r.code).toContain('    @JsonProperty("order_id")\n    private int orderId;');
    expect(r.code).toContain('    public static class Item {');
    expect(r.code).toContain('    public boolean isIsPaid() {');
    expect(r.code).toContain('    public void setOrderId(int orderId) {');
    expect(r.files.map((f) => f.path)).toContain('com/example/model/Item.java');
  });

  it('uses boxed types for nullable values and supports records and Lombok', () => {
    expect(generateJava({ items: [{ n: 1 }, { n: null }] }).code).toContain('private Integer n;');
    expect(generateJava(spec, { style: 'record', jackson: false }).code).toContain(
      'public record Root(\n    int orderId,\n    String customerName,\n    double totalAmount\n) {}',
    );
    const lombok = generateJava(spec, { style: 'lombok', packageName: '' }).code;
    expect(lombok).toContain('@Data\n@NoArgsConstructor\n@AllArgsConstructor\npublic class Root {');
    expect(lombok).not.toContain('package');
    expect(lombok).not.toContain('getOrderId');
  });

  it('escapes Java keywords', () => {
    expect(generateJava({ class: 1, new: 2 }).code).toContain('private int class_;');
  });
});

describe('Python', () => {
  it('generates dataclasses with defaults after required fields and dependency order', () => {
    const code = generatePython({ maybe: null, name: 'a', child: { x: 1 } }).code;
    expect(code).toContain(
      '@dataclass\nclass Child:\n    x: int\n\n\n@dataclass\nclass Root:\n    name: str\n    child: Child\n    maybe: Any = None',
    );
    expect(code).toContain('from __future__ import annotations');
  });

  it('orders classes dependencies-first while keeping declaration order', () => {
    const classes = generatePython(order)
      .code.split('\n')
      .filter((l) => l.startsWith('class '))
      .map((l) => l.slice(6, -1));
    expect(classes).toEqual(['ShippingAddress', 'Item', 'Experiments', 'Metadata', 'Root']);
  });

  it('generates pydantic models with aliases', () => {
    const code = generatePython(
      { orderId: 1, 'first name': 'A', when: '2026-01-01T00:00:00Z' },
      { style: 'pydantic' },
    ).code;
    expect(code).toContain('model_config = ConfigDict(populate_by_name=True)');
    expect(code).toContain('order_id: int = Field(alias="orderId")');
    expect(code).toContain('when: datetime');
    expect(code).toContain('from pydantic import BaseModel, ConfigDict, Field');
  });

  it('generates TypedDicts (functional syntax for non-identifier keys)', () => {
    expect(generatePython({ a: 1, items: [{ x: 1 }, {}] }, { style: 'typeddict' }).code).toContain(
      'class Item(TypedDict):\n    x: NotRequired[int]',
    );
    expect(generatePython({ 'first name': 'a' }, { style: 'typeddict' }).code).toContain(
      'Root = TypedDict(\n    "Root",\n    {\n        "first name": str,\n    },\n)',
    );
  });
});

describe('SQL table', () => {
  it('normalizes arrays into child tables with foreign keys', () => {
    const code = generateSqlTable(order, { tableName: 'orders' }).code;
    expect(code).toContain('CREATE TABLE orders (\n  order_id INTEGER PRIMARY KEY,');
    expect(code).toContain('  total_amount NUMERIC(10,2) NOT NULL,');
    expect(code).toContain('  shipping_address_city TEXT NOT NULL,');
    expect(code).toContain(
      'CONSTRAINT fk_order_items_orders FOREIGN KEY (order_id) REFERENCES orders (order_id) ON DELETE CASCADE',
    );
    expect(code).toContain('CREATE TABLE order_item_tags (');
  });

  it('supports JSON columns, surrogate keys and dialect-specific types/quoting', () => {
    const mssql = generateSqlTable(
      { name: 'x', user: { a: 1 }, tags: ['a'] },
      { dialect: 'mssql', tableName: 'order', objects: 'json', arrays: 'json' },
    ).code;
    expect(mssql).toContain(
      'CREATE TABLE [order] (\n  id BIGINT IDENTITY(1,1) PRIMARY KEY,\n  name NVARCHAR(50) NOT NULL,\n  [user] NVARCHAR(MAX) NOT NULL,\n  tags NVARCHAR(MAX) NOT NULL\n);',
    );
    expect(generateSqlTable({ id: 'x' }, { dialect: 'mysql', tableName: 'events' }).code).toContain(
      'id VARCHAR(50) PRIMARY KEY',
    );
    expect(generateSqlTable({ n: 1 }, { dialect: 'sqlite' }).code).toContain(
      'id INTEGER PRIMARY KEY AUTOINCREMENT',
    );
  });

  it('escapes backslashes in MySQL INSERTs so values cannot end the string early', () => {
    const code = generateSqlTable([{ id: 1, name: "a\\' OR 1=1 -- " }], {
      dialect: 'mysql',
      tableName: 'people',
      includeInserts: true,
    }).code;
    expect(code).toContain("(1, 'a\\\\'' OR 1=1 -- ')");
  });

  it('generates escaped INSERT statements', () => {
    const code = generateSqlTable(
      [
        { id: 1, name: "O'Neil", ok: true, at: null },
        { id: 2, name: 'B', ok: false },
      ],
      { dialect: 'mssql', tableName: 'people', includeInserts: true },
    ).code;
    expect(code).toContain(
      "INSERT INTO people (id, name, ok, at) VALUES\n  (1, N'O''Neil', 1, NULL),\n  (2, N'B', 0, NULL);",
    );
    expect(
      generateSqlTable([{ id: 1, ok: true }], { dialect: 'postgresql', includeInserts: true }).code,
    ).toContain('(1, TRUE)');
  });
});
