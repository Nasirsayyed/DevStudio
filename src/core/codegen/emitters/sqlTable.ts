import type { SqlDialect } from '../../sql/dialects';

export interface SqlTableOptions {
  dialect: SqlDialect;
  /** Root table name (snake_case recommended). */
  tableName: string;
  /** Nested objects: flatten into prefixed columns, or store as JSON. */
  objects: 'flatten' | 'json';
  /** Arrays: normalize into child tables with foreign keys, or store as JSON. */
  arrays: 'child-tables' | 'json';
  /** Use an `id`-like column as primary key when present; otherwise add a surrogate key. */
  detectPrimaryKey: boolean;
  /** Also emit INSERT statements for the sample data (root rows, up to 1,000). */
  includeInserts: boolean;
}

export const DEFAULT_SQL_TABLE_OPTIONS: SqlTableOptions = {
  dialect: 'postgresql',
  tableName: 'root',
  objects: 'flatten',
  arrays: 'child-tables',
  detectPrimaryKey: true,
  includeInserts: false,
};

const RESERVED = new Set(
  'add all alter and any as asc authorization backup begin between by cascade case check close column commit constraint create cross current current_date current_time current_timestamp current_user cursor database default delete desc distinct drop else end escape except exec exists fetch file for foreign from full function grant group having identity if in index inner insert intersect into is join key left like limit merge natural not null of offset on open option or order outer over percent plan primary procedure public references return revoke right role rollback row rows schema select session set some table then to top transaction trigger union unique update user using values view when where while with year month day hour minute second date time timestamp type value values level status comment position'.split(
    ' ',
  ),
);

const MAX_INSERT_ROWS = 1000;

interface Column {
  name: string;
  type: string;
  notNull: boolean;
  /** How to extract the value from a source object (null = generated). */
  path: string[] | null;
  json: boolean;
}

interface Table {
  name: string;
  columns: Column[];
  primaryKey: string;
  /** Surrogate identity key (generated by the database). */
  surrogate: boolean;
  foreignKey?: { column: string; refTable: string; refColumn: string };
}

class SqlEmitter {
  readonly tables: Table[] = [];
  readonly notes: string[] = [];
  private readonly o: SqlTableOptions;
  private readonly classes: Map<string, ModelClass>;
  private readonly tableNames = new NameScope([], true);

  constructor(o: SqlTableOptions, model: TypeModel) {
    this.o = o;
    this.classes = new Map(model.classes.map((c) => [c.name, c]));
  }

  quote(name: string): string {
    if (/^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED.has(name)) return name;
    switch (this.o.dialect) {
      case 'mssql':
        return `[${name.replace(/]/g, ']]')}]`;
      case 'mysql':
        return `\`${name.replace(/`/g, '``')}\``;
      default:
        return `"${name.replace(/"/g, '""')}"`;
    }
  }

  private stringType(maxLength: number): string {
    const sizes = [50, 100, 255, 1000];
    const size = sizes.find((s) => maxLength <= s);
    switch (this.o.dialect) {
      case 'mssql':
        return size ? `NVARCHAR(${size})` : 'NVARCHAR(MAX)';
      case 'mysql':
        return size ? `VARCHAR(${size})` : 'TEXT';
      default:
        return 'TEXT';
    }
  }

  jsonType(): string {
    return { mssql: 'NVARCHAR(MAX)', postgresql: 'JSONB', mysql: 'JSON', sqlite: 'TEXT' }[
      this.o.dialect
    ];
  }

  scalarType(t: TypeRef): string {
    const d = this.o.dialect;
    switch (t.kind) {
      case 'string':
        if (t.format === 'date-time')
          return {
            mssql: 'DATETIMEOFFSET',
            postgresql: 'TIMESTAMPTZ',
            mysql: 'DATETIME',
            sqlite: 'TEXT',
          }[d];
        if (t.format === 'date') return d === 'sqlite' ? 'TEXT' : 'DATE';
        if (t.format === 'uuid')
          return {
            mssql: 'UNIQUEIDENTIFIER',
            postgresql: 'UUID',
            mysql: 'CHAR(36)',
            sqlite: 'TEXT',
          }[d];
        return this.stringType(t.maxLength);
      case 'integer':
        if (d === 'sqlite') return 'INTEGER';
        return t.long ? 'BIGINT' : d === 'postgresql' ? 'INTEGER' : 'INT';
      case 'number': {
        if (d === 'sqlite') return 'REAL';
        const scale = Math.min(Math.max(2, t.scale), 10);
        const precision = Math.min(38, Math.max(10, t.integerDigits + scale + 2));
        return `${d === 'postgresql' ? 'NUMERIC' : 'DECIMAL'}(${precision},${scale})`;
      }
      case 'boolean':
        return { mssql: 'BIT', postgresql: 'BOOLEAN', mysql: 'BOOLEAN', sqlite: 'INTEGER' }[d];
      default:
        return this.jsonType();
    }
  }

  private identity(): string {
    return {
      mssql: 'BIGINT IDENTITY(1,1)',
      postgresql: 'BIGINT GENERATED ALWAYS AS IDENTITY',
      mysql: 'BIGINT AUTO_INCREMENT',
      sqlite: 'INTEGER',
    }[this.o.dialect];
  }

  /** Builds a table (and child tables) from a class. */
  buildTable(c: ModelClass, name: string, parent?: { table: Table; fkColumn: string }): Table {
    const table: Table = {
      name: this.tableNames.claim(name),
      columns: [],
      primaryKey: 'id',
      surrogate: true,
    };
    this.tables.push(table);
    const colScope = new NameScope([], true);
    const pending: (() => void)[] = [];

    const addColumns = (
      cls: ModelClass,
      prefix: string,
      pathPrefix: string[],
      parentNullable: boolean,
    ) => {
      for (const p of cls.properties) {
        const colName = colScope.claim(
          toIdentifier(prefix ? `${prefix}_${p.jsonName}` : p.jsonName, toSnakeCase, 'value', 'c_'),
        );
        const nullable = parentNullable || p.optional || p.type.nullable;
        const t = p.type;
        const path = [...pathPrefix, p.jsonName];
        if (t.kind === 'class' && this.o.objects === 'flatten') {
          const nested = this.classes.get(t.name);
          if (nested) {
            addColumns(nested, colName, path, nullable);
            continue;
          }
        }
        if (t.kind === 'array' && this.o.arrays === 'child-tables') {
          pending.push(() => {
            this.childTable(
              t.items,
              `${singularizeName(table.name)}_${toSnakeCase(p.jsonName) || 'items'}`,
              table,
            );
          });
          continue;
        }
        const json =
          t.kind === 'class' ||
          t.kind === 'array' ||
          t.kind === 'dictionary' ||
          t.kind === 'union' ||
          t.kind === 'any';
        table.columns.push({
          name: colName,
          type: json ? this.jsonType() : this.scalarType(t),
          notNull: !nullable && t.kind !== 'any',
          path,
          json,
        });
      }
    };

    addColumns(c, '', [], false);

    if (parent) {
      const parentPk = parent.table.columns.find((col) => col.name === parent.table.primaryKey);
      const fkType = parent.table.surrogate ? 'BIGINT' : (parentPk?.type ?? 'BIGINT');
      const fkName = colScope.has(parent.fkColumn)
        ? colScope.claim(`${parent.fkColumn}_ref`)
        : colScope.claim(parent.fkColumn);
      table.columns.unshift({
        name: fkName,
        type: this.o.dialect === 'sqlite' && parent.table.surrogate ? 'INTEGER' : fkType,
        notNull: true,
        path: null,
        json: false,
      });
      table.foreignKey = {
        column: fkName,
        refTable: parent.table.name,
        refColumn: parent.table.primaryKey,
      };
    }

    // Natural primary key: "id" or "<table>_id" with a scalar, non-null value.
    const singular = singularizeName(table.name);
    const natural =
      this.o.detectPrimaryKey && !parent
        ? table.columns.find(
            (col) =>
              (col.name === 'id' || col.name === `${singular}_id`) && col.notNull && !col.json,
          )
        : undefined;
    if (natural) {
      table.primaryKey = natural.name;
      table.surrogate = false;
    } else {
      const pk = colScope.has('id') ? colScope.claim(`${singular}_key`) : 'id';
      table.primaryKey = pk;
      table.columns.unshift({
        name: pk,
        type: this.identity(),
        notNull: true,
        path: null,
        json: false,
      });
    }

    for (const run of pending) run();
    return table;
  }

  private childTable(items: TypeRef, name: string, parent: Table): void {
    // FK column: reuse a natural key name ("order_id"), otherwise "<parent singular>_<pk>".
    const singular = singularizeName(parent.name);
    const fk =
      !parent.surrogate && parent.primaryKey.startsWith(`${singular}_`)
        ? parent.primaryKey
        : `${singular}_${parent.primaryKey}`;
    if (items.kind === 'class') {
      const cls = this.classes.get(items.name);
      if (cls) {
        this.buildTable(cls, name, { table: parent, fkColumn: fk });
        return;
      }
    }
    // Array of scalars → (parent_fk, position, value)
    const valueClass: ModelClass = {
      name,
      properties: [{ jsonName: 'value', type: items, optional: false }],
    };
    this.buildTable(valueClass, name, { table: parent, fkColumn: fk });
  }

  createStatement(t: Table): string {
    const lines = t.columns.map((col) => {
      const pk = col.name === t.primaryKey ? ' PRIMARY KEY' : '';
      const autoinc = this.o.dialect === 'sqlite' && pk && t.surrogate ? ' AUTOINCREMENT' : '';
      const notNull = col.notNull && !pk ? ' NOT NULL' : '';
      return `  ${this.quote(col.name)} ${col.type}${pk}${autoinc}${notNull}`;
    });
    if (t.foreignKey) {
      lines.push(
        `  CONSTRAINT ${this.quote(`fk_${t.name}_${t.foreignKey.refTable}`)} FOREIGN KEY (${this.quote(t.foreignKey.column)}) REFERENCES ${this.quote(t.foreignKey.refTable)} (${this.quote(t.foreignKey.refColumn)}) ON DELETE CASCADE`,
      );
    }
    return `CREATE TABLE ${this.quote(t.name)} (\n${lines.join(',\n')}\n);`;
  }

  literal(v: JsonValue | undefined, col: Column): string {
    if (v === undefined || v === null) return 'NULL';
    if (col.json || typeof v === 'object') return this.stringLiteral(JSON.stringify(v));
    if (typeof v === 'boolean') {
      if (this.o.dialect === 'postgresql' || this.o.dialect === 'mysql')
        return v ? 'TRUE' : 'FALSE';
      return v ? '1' : '0';
    }
    if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
    return this.stringLiteral(v);
  }

  private stringLiteral(s: string): string {
    return sqlStringLiteral(s, this.o.dialect);
  }

  insertStatements(table: Table, rows: JsonValue[]): string[] {
    const cols = table.columns.filter((c) => c.path !== null);
    if (cols.length === 0) return [];
    const header = `INSERT INTO ${this.quote(table.name)} (${cols.map((c) => this.quote(c.name)).join(', ')}) VALUES`;
    const tuples = rows.slice(0, MAX_INSERT_ROWS).map((row) => {
      const values = cols.map((c) => {
        let v: JsonValue | undefined = row;
        for (const key of c.path ?? [])
          v = isJsonObject(v) && Object.prototype.hasOwnProperty.call(v, key) ? v[key] : undefined;
        return this.literal(v, c);
      });
      return `  (${values.join(', ')})`;
    });
    if (rows.length > MAX_INSERT_ROWS)
      this.notes.push(`Only the first ${MAX_INSERT_ROWS} rows were turned into INSERT statements.`);
    return tuples.length ? [`${header}\n${tuples.join(',\n')};`] : [];
  }
}

export function generateSqlTable(
  value: JsonValue,
  options: Partial<SqlTableOptions> = {},
): GeneratedCode {
  const o: SqlTableOptions = { ...DEFAULT_SQL_TABLE_OPTIONS, ...options };
  const tableName = toIdentifier(o.tableName, toSnakeCase, 'root', 't_');
  const model = inferTypeModel(value, { rootName: tableName, detectDictionaries: true });
  const rootClass = model.classes.find((c) => c.name === model.rootClass);
  if (!rootClass) throw new Error('Missing root class');
  const e = new SqlEmitter(o, model);
  const root = e.buildTable(rootClass, tableName);

  const statements = e.tables.map((t) => e.createStatement(t));
  if (o.includeInserts) {
    const rows = model.rootIsArray && Array.isArray(value) ? value : [value];
    const inserts = e.insertStatements(root, rows);
    if (inserts.length) statements.push(...inserts);
    if (e.tables.length > 1)
      e.notes.push(
        'INSERT statements are generated for the root table only; child-table rows depend on generated keys.',
      );
  }
  const header = `-- Generated by DevStudio (${{ mssql: 'SQL Server', postgresql: 'PostgreSQL', mysql: 'MySQL', sqlite: 'SQLite' }[o.dialect]}). Review types, lengths and keys before use.`;
  const code = `${header}\n\n${statements.join('\n\n')}\n`;
  return { code, files: [{ path: `${tableName}.sql`, content: code }], notes: e.notes };
}
