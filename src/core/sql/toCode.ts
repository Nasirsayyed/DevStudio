import type { ModelClass, ModelProperty, TypeModel, TypeRef } from '../codegen/model';
import { generateCSharpFromModel, type CSharpOptions } from '../codegen/emitters/csharp';
import {
  generateTypeScriptFromModel,
  type TypeScriptOptions,
} from '../codegen/emitters/typescript';
import { singularizeName, toCamelCase, toPascalCase } from '../codegen/naming';
import type { GeneratedCode } from '../codegen/model';
import type { ColumnModel, TableModel } from './schema';

/** Maps SQL column types to the language-neutral type model used by every code generator. */
export function sqlTypeToRef(c: ColumnModel): TypeRef {
  const t = c.type.toUpperCase();
  const nullable = c.nullable;
  if (/^(BIG)?SERIAL8?$|^BIGINT$|^INT8$/.test(t) || t === 'BIGSERIAL')
    return { kind: 'integer', long: true, nullable };
  if (/^(BIT|BOOL|BOOLEAN)$/.test(t) || (t === 'TINYINT' && c.length === 1))
    return { kind: 'boolean', nullable };
  if (/^(SMALL|TINY|MEDIUM)?INT(EGER)?\d?$|^(SMALL)?SERIAL\d?$/.test(t))
    return { kind: 'integer', long: false, nullable };
  if (/^(DECIMAL|NUMERIC|MONEY|SMALLMONEY|DEC)$/.test(t))
    return {
      kind: 'number',
      integerDigits: Math.max(0, (c.length ?? 18) - (c.scale ?? 0)),
      scale: c.scale ?? (t.includes('MONEY') ? 4 : 0),
      nullable,
    };
  if (/^(FLOAT\d?|REAL|DOUBLE( PRECISION)?)$/.test(t))
    return { kind: 'number', integerDigits: 0, scale: 0, float: true, nullable };
  if (/^(UUID|UNIQUEIDENTIFIER)$/.test(t))
    return { kind: 'string', format: 'uuid', maxLength: 36, nullable };
  if (t === 'DATE') return { kind: 'string', format: 'date', maxLength: 10, nullable };
  if (
    /^(DATETIME\d?|SMALLDATETIME|DATETIMEOFFSET|TIMESTAMP(TZ)?|TIMESTAMP WITH(OUT)? TIME ZONE)$/.test(
      t,
    )
  )
    return { kind: 'string', format: 'date-time', maxLength: 0, nullable };
  if (/^(JSON|JSONB)$/.test(t)) return { kind: 'any', nullable };
  return { kind: 'string', maxLength: c.length ?? 0, nullable };
}

export interface TablesToModelOptions {
  /** Property names: the column names as they are, or camelCase (TypeScript). */
  propertyNames: 'column' | 'camel';
}

export function tablesToModel(
  tables: readonly TableModel[],
  options: Partial<TablesToModelOptions> = {},
): TypeModel {
  const classes: ModelClass[] = tables.map((t) => ({
    name: toPascalCase(singularizeName(t.name)) || 'Entity',
    table: { name: t.name, schema: t.schema },
    properties: t.columns.map((c): ModelProperty => ({
      jsonName: options.propertyNames === 'camel' ? toCamelCase(c.name) || c.name : c.name,
      type: sqlTypeToRef(c),
      optional: false,
      column: {
        name: c.name,
        sqlType: c.type,
        primaryKey: c.primaryKey,
        identity: c.identity,
        maxLength: c.length,
      },
    })),
  }));
  const first = classes[0]?.name ?? 'Entity';
  return {
    root: { kind: 'class', name: first, nullable: false },
    rootClass: first,
    rootIsArray: false,
    classes,
  };
}

export type SqlCSharpOptions = Pick<
  CSharpOptions,
  | 'namespace'
  | 'fileScopedNamespace'
  | 'nullableReferenceTypes'
  | 'typeKind'
  | 'dateType'
  | 'requiredMembers'
> & { annotations: boolean };

export function tablesToCSharp(tables: readonly TableModel[], o: SqlCSharpOptions): GeneratedCode {
  return generateCSharpFromModel(
    tablesToModel(tables),
    {
      ...o,
      attributes: o.annotations ? 'data-annotations' : 'none',
      attributeMode: 'when-different',
      numberType: 'decimal',
      useGuid: true,
      collectionType: 'List',
    },
    [
      `// Generated by DevStudio from ${String(tables.length)} CREATE TABLE ${tables.length === 1 ? 'statement' : 'statements'}.`,
    ],
  );
}

export type SqlTypeScriptOptions = Pick<
  TypeScriptOptions,
  'declaration' | 'readonly' | 'dateType' | 'exportTypes'
> &
  TablesToModelOptions;

export function tablesToTypeScript(
  tables: readonly TableModel[],
  o: SqlTypeScriptOptions,
): GeneratedCode {
  return generateTypeScriptFromModel(
    tablesToModel(tables, { propertyNames: o.propertyNames }),
    {
      declaration: o.declaration,
      readonly: o.readonly,
      dateType: o.dateType,
      exportTypes: o.exportTypes,
    },
    `// Generated by DevStudio from ${String(tables.length)} CREATE TABLE ${tables.length === 1 ? 'statement' : 'statements'}.`,
  );
}
