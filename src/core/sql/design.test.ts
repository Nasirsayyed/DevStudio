import initSqlJs from 'sql.js';
import { describe, expect, it } from 'vitest';
import { ParseError, ValidationError } from '../errors/AppError';
import {
  designFromTables,
  emptyDesign,
  generateDdl,
  newColumn,
  newTable,
  parseDesign,
  portableType,
  type SchemaDesign,
  validateDesign,
} from './design';
import { parseTables } from './schema';

const DDL = `CREATE TABLE customers (id SERIAL PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE, balance NUMERIC(10,2) DEFAULT 0);
CREATE TABLE orders (id BIGSERIAL PRIMARY KEY, customer_id INT NOT NULL REFERENCES customers(id) ON DELETE CASCADE, placed_at TIMESTAMPTZ NOT NULL, meta JSONB);`;

const design = () => designFromTables(parseTables(DDL, 'postgresql'));

describe('schema designer model', () => {
  it('imports CREATE TABLE scripts with types, keys and relations', () => {
    const d = design();
    expect(d.tables.map((t) => t.name)).toEqual(['customers', 'orders']);
    expect(
      d.tables[0]?.columns.map((c) => [c.name, c.type, c.length, c.scale, c.identity, c.unique]),
    ).toEqual([
      ['id', 'INTEGER', null, null, true, false],
      ['email', 'VARCHAR', 255, null, false, true],
      ['balance', 'DECIMAL', 10, 2, false, false],
    ]);
    expect(d.relations).toHaveLength(1);
    expect(d.relations[0]).toMatchObject({
      onDelete: 'CASCADE',
      fromTable: d.tables[1]?.id,
      toTable: d.tables[0]?.id,
    });
    expect(portableType('TINYINT', 1).type).toBe('BOOLEAN');
    expect(portableType('NVARCHAR', null).type).toBe('TEXT');
    expect(portableType('DATETIMEOFFSET', null).type).toBe('TIMESTAMPTZ');
  });

  it('generates DDL per dialect in dependency order', () => {
    const d = design();
    // Reverse the tables: orders depends on customers, so customers must still come first.
    d.tables.reverse();
    const pg = generateDdl(d, 'postgresql').sql;
    expect(pg.indexOf('CREATE TABLE customers')).toBeLessThan(pg.indexOf('CREATE TABLE orders'));
    expect(pg).toContain('  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,');
    expect(pg).toContain('  balance NUMERIC(10, 2) DEFAULT 0,');
    expect(pg).toContain(
      '  CONSTRAINT fk_orders_customer_id FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE',
    );
    const ms = generateDdl(d, 'mssql', { dropExisting: true }).sql;
    expect(ms.startsWith('DROP TABLE IF EXISTS orders;\nDROP TABLE IF EXISTS customers;')).toBe(
      true,
    );
    expect(ms).toContain('  id INT IDENTITY(1,1) NOT NULL,');
    expect(ms).toContain('  email NVARCHAR(255) NOT NULL UNIQUE,');
    expect(ms).toContain('  placed_at DATETIMEOFFSET NOT NULL,');
    expect(ms).toContain('  meta NVARCHAR(MAX),');
    const my = generateDdl(d, 'mysql', { quoteAll: true }).sql;
    expect(my).toContain('  `id` BIGINT AUTO_INCREMENT NOT NULL,');
    expect(my).toContain(') ENGINE=InnoDB;');
  });

  it('generates SQLite DDL that SQLite actually accepts and enforces', async () => {
    const SQL = await initSqlJs();
    const db = new SQL.Database();
    const { sql } = generateDdl(design(), 'sqlite', { dropExisting: true });
    expect(sql).toContain('  id INTEGER PRIMARY KEY AUTOINCREMENT,');
    db.run('PRAGMA foreign_keys = ON;');
    db.run(sql);
    db.run("INSERT INTO customers (email) VALUES ('a@example.com');");
    db.run("INSERT INTO orders (customer_id, placed_at) VALUES (1, '2024-01-01');");
    expect(() => db.run("INSERT INTO orders (customer_id, placed_at) VALUES (99, 'x');")).toThrow(
      /FOREIGN KEY/,
    );
    db.run('DELETE FROM customers;');
    expect(db.exec('SELECT COUNT(*) FROM orders')[0]?.values[0]?.[0]).toBe(0);
    db.close();
  });

  it('defers circular references to ALTER TABLE', () => {
    const a = newTable('a');
    const b = newTable('b');
    const aRef = newColumn({ name: 'b_id', type: 'INTEGER', length: null });
    const bRef = newColumn({ name: 'a_id', type: 'INTEGER', length: null });
    a.columns.push(aRef);
    b.columns.push(bRef);
    const d: SchemaDesign = {
      version: 1,
      tables: [a, b],
      relations: [
        {
          id: 'r1',
          fromTable: a.id,
          fromColumn: aRef.id,
          toTable: b.id,
          toColumn: b.columns[0]?.id ?? '',
          onDelete: 'NO ACTION',
        },
        {
          id: 'r2',
          fromTable: b.id,
          fromColumn: bRef.id,
          toTable: a.id,
          toColumn: a.columns[0]?.id ?? '',
          onDelete: 'SET NULL',
        },
      ],
    };
    const { sql } = generateDdl(d, 'postgresql');
    expect(sql).toContain(
      '-- Circular references are added after every table exists.\nALTER TABLE a ADD CONSTRAINT fk_a_b_id FOREIGN KEY (b_id) REFERENCES b (id);',
    );
    expect(sql).toContain('ON DELETE SET NULL');
  });

  it('reports design problems and refuses to generate invalid DDL', () => {
    const t = newTable('users');
    t.columns.push(
      newColumn({ name: 'ID', type: 'TEXT', identity: true }),
      newColumn({ name: '' }),
    );
    const d: SchemaDesign = {
      version: 1,
      tables: [t, newTable('Users'), { ...newTable('empty'), columns: [] }],
      relations: [],
    };
    const messages = validateDesign(d).map((i) => i.message);
    expect(messages).toEqual(
      expect.arrayContaining([
        'There are several tables named "users".',
        '"users" has several columns named "ID".',
        '"users.ID" is auto-increment but not an integer.',
        'A column of "users" has no name.',
        'Table "empty" has no columns.',
      ]),
    );
    expect(() => generateDdl(d, 'sqlite')).toThrow(ValidationError);
    expect(() => generateDdl(emptyDesign(), 'sqlite')).toThrow('Add a table to generate DDL.');
  });

  it('round-trips design files and rejects invalid or polluted ones', () => {
    const d = design();
    expect(parseDesign(JSON.stringify(d))).toEqual(d);
    expect(() => parseDesign('{')).toThrow(ParseError);
    expect(() => parseDesign('{"version":2,"tables":[],"relations":[]}')).toThrow(/version/);
    expect(() =>
      parseDesign(
        '{"version":1,"tables":[{"id":"x","name":"t","columns":[{"type":"NOPE"}]}],"relations":[]}',
      ),
    ).toThrow(ValidationError);
    const polluted = parseDesign('{"version":1,"tables":[],"relations":[],"__proto__":{"x":1}}');
    expect(({} as Record<string, unknown>).x).toBeUndefined();
    expect(polluted.tables).toEqual([]);
  });
});
